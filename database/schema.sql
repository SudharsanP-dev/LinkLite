-- LinkLite database schema for Microsoft SQL Server (2016 or newer)
--
-- In SSMS: open this file, press F5 (Execute). It is safe to run more than once.
-- Or from the terminal: npm run db:init
--
-- (On Azure SQL Database you can't run CREATE DATABASE here. Create the database in
--  the Azure portal, connect to it, and run only the CREATE TABLE part.)

IF DB_ID(N'linklite') IS NULL
    CREATE DATABASE linklite;
GO

USE linklite;
GO

IF OBJECT_ID(N'dbo.urls', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.urls (
        id              BIGINT        IDENTITY(1,1) NOT NULL CONSTRAINT PK_urls PRIMARY KEY,
        -- Random ID generated by each browser; keeps one visitor's history separate from another's.
        owner_id        CHAR(36)      NOT NULL,
        -- BIN2 collation makes codes case-sensitive, so "aB3" and "ab3" are different links.
        short_code      VARCHAR(32)   COLLATE Latin1_General_100_BIN2 NOT NULL,
        original_url    NVARCHAR(2048) NOT NULL,
        clicks          INT           NOT NULL CONSTRAINT DF_urls_clicks DEFAULT 0,
        created_at      DATETIME2(0)  NOT NULL CONSTRAINT DF_urls_created DEFAULT SYSUTCDATETIME(),
        last_clicked_at DATETIME2(0)  NULL
    );

    CREATE UNIQUE INDEX uq_short_code ON dbo.urls (short_code);
    CREATE INDEX idx_owner_created ON dbo.urls (owner_id, created_at DESC);
END
GO

IF OBJECT_ID(N'dbo.users', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.users (
        id              CHAR(36)       NOT NULL CONSTRAINT PK_users PRIMARY KEY,
        display_name    NVARCHAR(80)   NOT NULL,
        email           NVARCHAR(254)  NOT NULL,
        password_hash   VARCHAR(100)  NOT NULL,
        role            VARCHAR(10)   NOT NULL CONSTRAINT DF_users_role DEFAULT 'user',
        is_active       BIT           NOT NULL CONSTRAINT DF_users_active DEFAULT 1,
        session_version INT           NOT NULL CONSTRAINT DF_users_session_version DEFAULT 0,
        created_at      DATETIME2(0)  NOT NULL CONSTRAINT DF_users_created DEFAULT SYSUTCDATETIME(),
        CONSTRAINT CK_users_role CHECK (role IN ('user', 'admin'))
    );

    CREATE UNIQUE INDEX uq_users_email ON dbo.users (email);
END
GO

IF OBJECT_ID(N'dbo.auth_sessions', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.auth_sessions (
        sid         NVARCHAR(255) NOT NULL CONSTRAINT PK_auth_sessions PRIMARY KEY,
        session_data NVARCHAR(MAX) NOT NULL,
        expires_at  DATETIME2(0)  NOT NULL
    );

    CREATE INDEX idx_auth_sessions_expiry ON dbo.auth_sessions (expires_at);
END
GO
